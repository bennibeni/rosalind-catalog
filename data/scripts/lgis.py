def lettura(filename):
    with open(filename) as f:
         _ = int(f.readline().replace("\n",""))  # count of elements, unused (len(n) is used instead)
         n = f.readline().replace("\n","").split()
    return n     

def gt(x, y):
   return int(x) > int(y);

def lt(x, y):
   return int(y) > int(x);

def main():
    funcs = (gt, lt)
    n = lettura("dataset.txt")
    for func in funcs:
        arr = []
        for i in range(len(n)):
            arr.append([0, 0])
        max_distance = 0;
        max_distance_i = 0;
        for i in range(len(n)):
            for j in range(i+1, len(n)):
                if func(n[j], n[i]):
                    old_distance = arr[i][0]
                    new_distance = arr[j][0]
                    if new_distance < old_distance+1:
                       arr[j][0] = old_distance+1; 
                       arr[j][1] = i; 
                       if old_distance+1 > max_distance:
                          max_distance = old_distance+1
                          max_distance_i = j

        prev = max_distance_i
        sol = []
        while(True):
           sol.insert(0, n[prev])
           if arr[prev][0] == 0:
             break
           prev = arr[prev][1]
        print(""," ".join(sol))
        #print("max_distance+1:"+str(max_distance+1)+"\n"+"sol.length:"+str(len(sol)))

